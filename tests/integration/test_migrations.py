"""Alembic migration round trip and model/migration parity on a real Postgres."""

from __future__ import annotations

import asyncio
from collections.abc import Iterator
from typing import Any

import pytest
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy.pool import NullPool

from tests.integration.dbutil import alembic, drop_database, in_thread, recreate_database, url_for
from ya_voy.db.base import Base

MIGRATED_DB = "yavoy_migration_test"
METADATA_DB = "yavoy_metadata_test"

EXPECTED_TABLES = {
    "stores",
    "couriers",
    "orders",
    "order_events",
    "inbound_events",
    "messages",
    "outbound_messages",
    "daily_reports",
    "report_revisions",
    "schedule_overrides",
    "parked_reactions",
}

# Constraint and index names written verbatim in docs/05-modelo-datos.md.
DOC_NAMED_OBJECTS = {
    "couriers_has_identity",
    "orders_one_draft_per_store",
    "orders_courier_matches_status",
    "orders_code_when_published",
    "schedule_overrides_one_pending_per_admin",
    "schedule_overrides_period",
    "schedule_overrides_window",
    "schedule_overrides_active",
    "schedule_overrides_status_by_kind",
    "schedule_overrides_business_date_by_kind",
    "messages_inbound_event_only_in",
    "messages_outbound_message_only_out",
    "outbound_messages_target_for_delete_edit",
    "outbound_messages_revision_for_document",
}

SNAPSHOT_QUERIES = {
    "tables": """
        SELECT tablename FROM pg_tables WHERE schemaname = 'public'
    """,
    "columns": """
        SELECT table_name, column_name, data_type, is_nullable, column_default,
               is_identity, identity_generation
          FROM information_schema.columns WHERE table_schema = 'public'
    """,
    "constraints": """
        SELECT conrelid::regclass::text, conname, pg_get_constraintdef(oid)
          FROM pg_constraint WHERE connamespace = 'public'::regnamespace
    """,
    "indexes": """
        SELECT tablename, indexname, indexdef FROM pg_indexes WHERE schemaname = 'public'
    """,
    "sequences": """
        SELECT sequencename FROM pg_sequences
         WHERE schemaname = 'public' AND sequencename NOT LIKE '%id_seq'
    """,
}


def snapshot(database_url: str) -> dict[str, set[tuple[Any, ...]]]:
    """Schema objects of the public schema, excluding Alembic's own bookkeeping table."""

    async def run() -> dict[str, set[tuple[Any, ...]]]:
        engine = create_async_engine(database_url, poolclass=NullPool)
        async with engine.connect() as conn:
            result = {
                name: {tuple(r) for r in (await conn.execute(text(sql))).all()}
                for name, sql in SNAPSHOT_QUERIES.items()
            }
        await engine.dispose()
        return {
            name: {r for r in rows if not any(str(v).startswith("alembic_version") for v in r)}
            for name, rows in result.items()
        }

    return in_thread(asyncio.run, run())


def create_all(database_url: str) -> None:
    async def run() -> None:
        engine = create_async_engine(database_url, poolclass=NullPool)
        async with engine.begin() as conn:
            await conn.run_sync(Base.metadata.create_all)
        await engine.dispose()

    in_thread(asyncio.run, run())


@pytest.fixture(scope="module")
def migrated_url() -> Iterator[str]:
    recreate_database(MIGRATED_DB)
    url = url_for(MIGRATED_DB)
    alembic(url, "upgrade", "head")
    yield url
    drop_database(MIGRATED_DB)


@pytest.fixture(scope="module")
def metadata_url() -> Iterator[str]:
    recreate_database(METADATA_DB)
    url = url_for(METADATA_DB)
    create_all(url)
    yield url
    drop_database(METADATA_DB)


def test_upgrade_creates_every_table(migrated_url: str) -> None:
    snap = snapshot(migrated_url)
    assert {t for (t,) in snap["tables"]} == EXPECTED_TABLES
    assert snap["sequences"] == {("order_code_seq",)}


def test_doc_named_constraints_and_indexes_exist(migrated_url: str) -> None:
    snap = snapshot(migrated_url)
    names = {r[1] for r in snap["constraints"]} | {r[1] for r in snap["indexes"]}
    assert names >= DOC_NAMED_OBJECTS


def test_migration_matches_models_exactly(migrated_url: str, metadata_url: str) -> None:
    """Columns, defaults, identity, CHECK/UNIQUE/FK definitions and index definitions
    (including partial WHERE clauses) are identical to Base.metadata.create_all()."""
    migrated, from_models = snapshot(migrated_url), snapshot(metadata_url)
    for kind in SNAPSHOT_QUERIES:
        assert migrated[kind] == from_models[kind], (
            kind,
            migrated[kind] ^ from_models[kind],
        )


def test_alembic_check_reports_no_pending_changes(migrated_url: str) -> None:
    try:
        alembic(migrated_url, "check")
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"models and migrations differ: {exc}")


def test_round_trip_upgrade_downgrade_upgrade(migrated_url: str) -> None:
    before = snapshot(migrated_url)

    alembic(migrated_url, "downgrade", "base")
    emptied = snapshot(migrated_url)
    assert all(not rows for rows in emptied.values()), emptied  # everything dropped

    alembic(migrated_url, "upgrade", "head")
    assert snapshot(migrated_url) == before

    alembic(migrated_url, "downgrade", "-1")
    alembic(migrated_url, "upgrade", "head")
    assert snapshot(migrated_url) == before
